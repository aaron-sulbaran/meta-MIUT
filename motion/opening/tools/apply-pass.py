"""apply-pass: copy one capture pass into the decks and write the recap's proof and facts.

usage: python3 apply-pass.py <passDir>
Reads <passDir>/recap-pass.json (from recap-pass.mjs), copies the chosen captures into
public/demo/deck/shared/captures at 2x, writes public/demo/deck/recap/proof.js, copies the
pass record to motion/opening/recap-pass.json, and rewrites facts.json's recap entries
from the same runs, so the screen and the number always come from one set of runs.
"""
import json
import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[3]
DECK = ROOT / "public/demo/deck"
CAPTURES = DECK / "shared/captures"
pass_dir = Path(sys.argv[1])
data = json.loads((pass_dir / "recap-pass.json").read_text())
timings = json.loads((ROOT / "motion/opening/timings-local.json").read_text())

RECAP_FILES = {
    "flyer": "recap-1-flyer.jpg",
    "walk": "recap-2-walk.jpg",
    "heard": "recap-3-heard.jpg",
    "replan": "recap-4-replan.jpg",
    "picks": "recap-5-picks.jpg",
    "hello": "recap-6-hello.jpg",
}
OTHER = {
    # The problem deck's payoff and the muse deck's discovery step, from the same pass.
    "list": ["list.jpg", "events-list.jpg"],
    "home": ["events-map.jpg"],
    "walk": ["walkhome.jpg"],
}


def to_jpg(src: Path, dest: Path) -> None:
    subprocess.run(["ffmpeg", "-y", "-loglevel", "error", "-i", str(src), "-vf", "scale=780:-2", "-q:v", "3", str(dest)], check=True)


proof = {}
for key, name in RECAP_FILES.items():
    entry = data[key]
    to_jpg(pass_dir / entry["chosen"], CAPTURES / name)
    seconds = entry["median"]
    if key == "heard":
        # No time stamp on that screen: the time is the transcription runs' median.
        seconds = round(timings["results"]["transcribe"]["medianMs"] / 1000, 1)
    proof[key] = {"file": name, "seconds": seconds, "box": entry["chosenBox"]}
for key, names in OTHER.items():
    for name in names:
        to_jpg(pass_dir / data[key]["chosen"], CAPTURES / name)

(DECK / "recap/proof.js").write_text(
    "/* Generated by motion/opening/tools/apply-pass.py from one capture pass\n"
    "   (motion/opening/recap-pass.json): each moment's median run, its own time, and where\n"
    "   that time stamp (or her words) sits on the 390 x 844 screen. */\n"
    f"window.RECAP_PROOF = {json.dumps(proof, indent=2)};\n"
)
(ROOT / "motion/opening/recap-pass.json").write_text(json.dumps(data, indent=2) + "\n")

METHOD = (
    "One capture pass by the deck builder on 2026-11-13 between 3:40 and 4:30 AM PT, against a local "
    "production build of main with the Muse key linked and the server clock set to the demo clock "
    "(3:05 PM ET; motion/opening/tools/demo-clock.cjs). Each run loads the real screen in a 390 x 844 "
    "frame as the stage does, as the right person, and reads the app's own time stamp "
    "(motion/opening/tools/recap-pass.mjs; every run in motion/opening/recap-pass.json). Steps the app "
    "keeps per run (re-plan, picks, hello) ran once per fresh server. The deck shows the median run's "
    "screen and that run's own number, so they cannot disagree."
)


def runs(key):
    return ", ".join(f"{r['seconds']}" for r in data[key]["runs"] if r.get("seconds") is not None)


t = timings["results"]["transcribe"]
transcribe_runs = ", ".join(f"{s['ms'] / 1000:.1f}" for s in t["samples"])
RECAP = [
    ("what-muse-did", "What Muse just did", "Aaron's decision via the lead (2026-11-13): a recap after the skit in the organizers' How AI powers it slot."),
    ("moment-1", f"Read the club's flyer; Muse Ember; {proof['flyer']['seconds']} seconds", f"{METHOD} Flyer read, as Jing (/organizer?handoff=story; the page calls /api/muse/extract/events with the flyer): runs {runs('flyer')} s, median {proof['flyer']['seconds']} s, shown with that run's screen (Read in {proof['flyer']['seconds']} s). Model: muse-ember-1.0 (lib/muse/client.ts)."),
    ("moment-2", f"Planned her walk home; Muse Ember; {proof['walk']['seconds']} seconds", f"{METHOD} Walk home, as Jolyn (/?plan=home): runs {runs('walk')} s, median {proof['walk']['seconds']} s, shown with that run's screen (planned {proof['walk']['seconds']} s). Model: muse-ember-1.0."),
    ("moment-3", f"Heard what she said; Muse Voice Transcribe; {proof['heard']['seconds']} seconds", f"Transcription has no time stamp on the stage's screen, so its time is the median of five live calls to /api/muse/transcribe with the spoken re-plan line as a 16 kHz WAV ({transcribe_runs} s; motion/opening/timings-local.json, measured 2:13 AM PT). The screen is the stage's map after a heard message (from the same pass), her words marked Said and ringed. Model: muse-voice-transcribe-1.0 (lib/muse/transcribe.ts)."),
    ("moment-4", f"Re-planned, sent the invite; Muse Ember; {proof['replan']['seconds']} seconds", f"{METHOD} Re-plan, as Jolyn (/?plan=home&auto=1): runs {runs('replan')} s, median {proof['replan']['seconds']} s, shown with that run's screen (asked {proof['replan']['seconds']} s, Sent to Lisa). Model: muse-ember-1.0."),
    ("moment-5", f"Built her first feed; Muse Ember; {proof['picks']['seconds']} seconds", f"{METHOD} Trish's first picks (/?first=1, which calls /api/curate): runs {runs('picks')} s, median {proof['picks']['seconds']} s, shown with that run's screen (picked {proof['picks']['seconds']} s). Model: muse-ember-1.0."),
    ("moment-6", f"Found people, wrote the hello; Muse Ember; {proof['hello']['seconds']} seconds", f"{METHOD} The skit's state replayed first (the story on the demo clock; Lisa, invited by Jolyn, going and open to company). Muse suggests Jolyn and Lisa, then writes Trish's hello: the hello's runs {runs('hello')} s, median {proof['hello']['seconds']} s, shown with that run's screen (Written by Muse, Live, {proof['hello']['seconds']} s). Two calls in this moment: who to go with (/api/social/events/[id]/muse, 1.5 to 1.9 s over HTTP, motion/opening/timings-people.json) and the hello. Model: muse-ember-1.0."),
    ("live-calls", "Every one a live call to Meta's Muse models. A recorded answer always says so on screen.", "Every moment above ran against the live models in this pass (seven calls across six moments; moment 6 is two). The product labels any recorded fallback on screen (SourceBadge, Recorded labels), per AGENTS.md."),
]
facts = json.loads((DECK / "facts.json").read_text())
facts["recap"] = [{"step": s, "text": text, "source": src} for s, text, src in RECAP]
(DECK / "facts.json").write_text(json.dumps(facts, indent=2, ensure_ascii=False) + "\n")
print(json.dumps({k: v["seconds"] for k, v in proof.items()}))
