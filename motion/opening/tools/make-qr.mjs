// make-qr: the round QR badge the decks show, as one self-contained SVG (vector, nothing
// fetched at runtime). High error correction, a full four-module quiet zone inside a white
// circle, ink on white; modules are only lightly rounded, so it scans first time from the
// back of a room on a projector.
// usage: node make-qr.mjs <qrcodeModuleDir> <url> <out.svg>
//   qrcodeModuleDir: a folder with the npm package qrcode@1.5.4 installed (kept out of the repo).
import { createRequire } from 'node:module';
import { writeFileSync } from 'node:fs';
import path from 'node:path';

const [modDir, url, out] = process.argv.slice(2);
const require = createRequire(path.join(path.resolve(modDir), 'package.json'));
const QRCode = require('qrcode');

const qr = QRCode.create(url, { errorCorrectionLevel: 'H' });
const n = qr.modules.size;
const dark = (r, c) => qr.modules.get(r, c) === 1;
const QUIET = 4;
/* The code plus its quiet zone must sit inside the circle, corners included. */
const D = Math.ceil((n + QUIET * 2) * Math.SQRT2) + 2;
const off = (D - n) / 2;
const R = 0.32;

const inFinder = (r, c) => {
  const corners = [[0, 0], [0, n - 7], [n - 7, 0]];
  return corners.some(([fr, fc]) => r >= fr && r < fr + 7 && c >= fc && c < fc + 7);
};

const parts = [];
for (let r = 0; r < n; r++) {
  for (let c = 0; c < n; c++) {
    if (!dark(r, c) || inFinder(r, c)) continue;
    parts.push(`<rect x="${(off + c).toFixed(2)}" y="${(off + r).toFixed(2)}" width="1" height="1" rx="${R}"/>`);
  }
}
/* Finder patterns: a rounded 7 x 7 ring with a rounded 3 x 3 center. */
for (const [fr, fc] of [[0, 0], [0, n - 7], [n - 7, 0]]) {
  const x = off + fc;
  const y = off + fr;
  parts.push(`<path fill-rule="evenodd" d="M${x + 1.6},${y} h3.8 a1.6,1.6 0 0 1 1.6,1.6 v3.8 a1.6,1.6 0 0 1 -1.6,1.6 h-3.8 a1.6,1.6 0 0 1 -1.6,-1.6 v-3.8 a1.6,1.6 0 0 1 1.6,-1.6 Z M${x + 1.9},${y + 1} h3.2 a0.9,0.9 0 0 1 0.9,0.9 v3.2 a0.9,0.9 0 0 1 -0.9,0.9 h-3.2 a0.9,0.9 0 0 1 -0.9,-0.9 v-3.2 a0.9,0.9 0 0 1 0.9,-0.9 Z"/>`);
  parts.push(`<rect x="${x + 2}" y="${y + 2}" width="3" height="3" rx="0.8"/>`);
}

const svg = `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 ${D} ${D}" role="img" aria-label="QR code to ${url}">
<!-- Generated by motion/opening/tools/make-qr.mjs: ${url}, error correction H, version ${qr.version}, ${n} modules, quiet zone ${QUIET}. -->
<circle cx="${D / 2}" cy="${D / 2}" r="${D / 2}" fill="#ffffff"/>
<g fill="#08090d">${parts.join('')}</g>
</svg>
`;
writeFileSync(out, svg);
console.log(JSON.stringify({ url, version: qr.version, modules: n, diameter: D, out }));
